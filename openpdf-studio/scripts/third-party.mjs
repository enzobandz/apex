// Generates THIRD_PARTY_NOTICES.md from `cargo metadata` (desktop app + CLI
// dependency graph) and the production npm dependency tree.
//
//   node scripts/third-party.mjs > THIRD_PARTY_NOTICES.md
//
// Fails if a dependency's license is not on the allow-list, so a copyleft
// or proprietary dependency cannot slip into a release unnoticed.

import { execFileSync } from "node:child_process";
import { readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ALLOWED = [
  "MIT",
  "Apache-2.0",
  "Apache-2.0 WITH LLVM-exception",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "ISC",
  "Zlib",
  "Unicode-3.0",
  "Unicode-DFS-2016",
  "MPL-2.0",
  "CC0-1.0",
  "0BSD",
  "BSL-1.0",
  "Unlicense",
  "CDLA-Permissive-2.0",
  "BlueOak-1.0.0",
];

function licenseOk(expr) {
  if (!expr) return false;
  // Any alternative of an OR expression being allowed is enough; every part of AND must be allowed.
  return expr
    .replace(/[()]/g, "")
    .split(/\s+OR\s+|\//)
    .some((alt) => alt.split(/\s+AND\s+/).every((l) => ALLOWED.includes(l.trim())));
}

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--filter-platform", hostTarget()], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  }),
);
const workspace = new Set(meta.workspace_members);
const resolveNodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
// Walk normal (non-dev, non-build) dependencies from the shipped binaries.
const roots = meta.packages.filter((p) => ["openpdf-studio", "opdf-cli"].includes(p.name)).map((p) => p.id);
const seen = new Set();
const stack = [...roots];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of resolveNodes.get(id)?.deps ?? []) {
    if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
  }
}
const crates = meta.packages
  .filter((p) => seen.has(p.id) && !workspace.has(p.id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? "(see repository)", repo: p.repository ?? "" }))
  .sort((a, b) => a.name.localeCompare(b.name));

function hostTarget() {
  const out = execFileSync("rustc", ["-vV"], { encoding: "utf8" });
  return out.match(/host: (.+)/)[1];
}

const appDir = join(root, "app");
const npmTree = JSON.parse(execFileSync("npm", ["ls", "--omit=dev", "--all", "--json"], { cwd: appDir, encoding: "utf8" }));
const npm = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    // Skip optional peers that are not installed, and pdf.js' Node-only
    // canvas binding (never bundled into the desktop app).
    if (!info.version || info.missing || name.startsWith("@napi-rs/canvas")) continue;
    const key = `${name}@${info.version}`;
    if (npm.has(key)) continue;
    const pj = join(appDir, "node_modules", name, "package.json");
    const pkg = existsSync(pj) ? JSON.parse(readFileSync(pj, "utf8")) : {};
    npm.set(key, { name, version: info.version, license: pkg.license ?? "(see package)" });
    walk(info.dependencies);
  }
})(npmTree.dependencies);
const npmList = [...npm.values()].sort((a, b) => a.name.localeCompare(b.name));

const bad = [...crates, ...npmList].filter((d) => !licenseOk(d.license));
if (bad.length) {
  console.error("Dependencies with licenses outside the allow-list:");
  for (const d of bad) console.error(`  ${d.name} ${d.version}: ${d.license}`);
  process.exit(1);
}

const rows = (list) => list.map((d) => `| ${d.name} | ${d.version} | ${d.license} |`).join("\n");
console.log(`# Third-party notices

OpenPDF Studio is licensed under the Mozilla Public License 2.0 (see LICENSE).
It includes the open-source components listed below, each under its own
license. This file is generated by \`node scripts/third-party.mjs\`; the
script fails if any dependency uses a license outside the project's
allow-list (${ALLOWED.join(", ")}).

Full license texts are distributed with each package (Cargo registry sources,
\`node_modules/<package>/LICENSE\`). pdf.js additionally ships the licenses of
its bundled decoders under \`public/pdfjs/wasm/LICENSE_*\` and of its fonts
under \`public/pdfjs/standard_fonts/LICENSE_*\`.

## Key components

| Component | Role | License |
|---|---|---|
| pdf.js (pdfjs-dist) | Rendering, text layer, search, forms, annotation editing, incremental saving | Apache-2.0 |
| lopdf | PDF object model: page operations, merge/split, encryption, writing | MIT |
| Tauri | Desktop shell and IPC | MIT OR Apache-2.0 |
| React | User interface | MIT |
| image-rs (image, zune-jpeg, png...) | Image decoding/encoding for images-to-PDF and optimisation | MIT OR Apache-2.0 |
| SQLite (via rusqlite, bundled) | Settings and recent files | Public domain (SQLite) / MIT |
| Lucide | Icons | ISC |

## Rust crates (${crates.length})

| Crate | Version | License |
|---|---|---|
${rows(crates)}

## npm packages shipped in the app (${npmList.length})

| Package | Version | License |
|---|---|---|
${rows(npmList)}
`);
